// Turns the downloaded bhavcopy zips into two things:
//
//   1. bhav-daily-240mo.json.part*.json — per-symbol daily OHLC + turnover,
//      chunked in exactly the shape dailyCacheIO.js already loads, so the
//      existing backtest scripts can read it without changes.
//   2. bhav-universe-240mo.json — each symbol's first and last trading day.
//      This is the point-in-time universe: it's what lets a backtest ask
//      "what was actually listed on this date" instead of assuming today's
//      survivors were always there.
//
// Run with: node scripts/parse-bhavcopy.js [--src=./bhav-raw] [--out=.]

import fs from "node:fs/promises";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const arg = (name, fallback) => {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.split("=")[1] : fallback;
};

const SRC = path.resolve(__dirname, arg("src", "./bhav-raw"));
const OUT = path.resolve(__dirname, arg("out", "."));
const SYMBOLS_PER_CHUNK = 50;
const BASE = "bhav-daily-240mo.json";

// Every archive is a single deflate entry. Read the central directory
// rather than the local header: the local header can carry a zero size
// when a data descriptor is used, which silently truncates the CSV.
function unzipSingle(buf) {
  let i = buf.length - 22;
  while (i >= 0 && buf.readUInt32LE(i) !== 0x06054b50) i--;
  if (i < 0) throw new Error("no end-of-central-directory record");
  const cd = buf.readUInt32LE(i + 16);
  const method = buf.readUInt16LE(cd + 10);
  const compSize = buf.readUInt32LE(cd + 20);
  const lh = buf.readUInt32LE(cd + 42);
  const start = lh + 30 + buf.readUInt16LE(lh + 26) + buf.readUInt16LE(lh + 28);
  const data = buf.subarray(start, start + compSize);
  return method === 0 ? data.toString("utf8") : zlib.inflateRawSync(data).toString("utf8");
}

// The date comes from the FILENAME, never the TIMESTAMP column. One real
// file (cm13JUL2020bhav.csv) writes its timestamp with a two-digit year,
// which produced 1,392 unparseable dates and crashed the backtest. The
// filename is generated by NSE and is unambiguous.
const MONTH_NUM = { JAN:"01",FEB:"02",MAR:"03",APR:"04",MAY:"05",JUN:"06",JUL:"07",AUG:"08",SEP:"09",OCT:"10",NOV:"11",DEC:"12" };
function dateFromFilename(name) {
  let m = /^cm(\d{2})([A-Z]{3})(\d{4})bhav/.exec(name);
  if (m) return `${m[3]}-${MONTH_NUM[m[2]]}-${m[1]}`;
  m = /_(\d{4})(\d{2})(\d{2})_F_/.exec(name);
  if (m) return `${m[1]}-${m[2]}-${m[3]}`;
  return null;
}

// Bhavcopy prints RAW traded prices — it does not adjust for splits or
// bonuses. Yahoo does, which is why this never surfaced before. Left
// uncorrected, SETFGOLD's 1:100 split reads as a one-day -99% crash, and a
// backtest books it as a catastrophic loss on a position that actually just
// became 100x the shares at 1/100 the price. Real cases in this window:
// SETFGOLD, VSTIND, TATAINVEST, VESUVIUS, IRB, RUSHIL, MOTISONS, NDL.
//
// NSE hands us the correction for free: on the ex-date it prints a
// PREVCLOSE that is already adjusted, so prevClose[t] / close[t-1] IS the
// ratio. Anything more than a couple of percent off 1.0 is a corporate
// action, not rounding. Prices before the action are multiplied by the
// cumulative ratio so the series is continuous, which is the standard
// back-adjustment every data vendor applies.
const ACTION_TOLERANCE = 0.02;
// A stated PREVCLOSE only refers to the bar before it when the two are
// actually consecutive sessions. Across a hole in the series it compares
// against whatever we last kept, which is not what NSE was quoting — and
// that reads as a corporate action that never happened.
//
// This is not hypothetical. BODALCHEM spent 67 days in the BE segment; with
// BE excluded the series had a 98-day hole, and 31-Aug-2026's stated
// previous close of 99.08 got compared against 25-May's 75.80. The 1.307
// ratio scaled every earlier price up 30%, which is why our history
// disagreed with Yahoo by ~23% while both agreed on today's price.
//
// BE rows are now kept, which removes most holes; this guard covers the
// rest — genuine suspensions, delisting gaps, thin symbols that simply
// did not trade.
const MAX_GAP_DAYS = 5;
let actionsFound = 0;
let gapsSkipped = 0;

function backAdjust(bars) {
  const factors = new Array(bars.length).fill(1);
  let cum = 1;
  for (let i = bars.length - 1; i >= 1; i--) {
    const prior = bars[i - 1].close;
    const stated = bars[i].prevClose;
    if (prior > 0 && stated > 0) {
      const ratio = stated / prior;
      if (Math.abs(ratio - 1) > ACTION_TOLERANCE) {
        const gap = (new Date(bars[i].date) - new Date(bars[i - 1].date)) / 86400000;
        if (gap <= MAX_GAP_DAYS) { cum *= ratio; actionsFound++; }
        else gapsSkipped++;
      }
    }
    factors[i - 1] = cum;
  }
  for (let i = 0; i < bars.length; i++) {
    const f = factors[i];
    if (f === 1) continue;
    bars[i].open *= f;
    bars[i].high *= f;
    bars[i].low *= f;
    bars[i].close *= f;
    // Turnover is a rupee figure and is unaffected by a split; share
    // counts are, so volume moves the other way to keep price x volume
    // consistent with the value actually traded that day.
    bars[i].volume = Math.round(bars[i].volume / f);
  }
}

// Second pass, for what PREVCLOSE misses. Demergers and ETF
// restructurings (360ONE, ABFRL, ABIRLANUVO, the ABSL ETFs) don't always
// get a restated PREVCLOSE, leaving 502 single-day moves of >55% in the
// first-pass output. Indian circuit filters cap most stocks near +/-20% a
// day, so a move that size is structural, not price action.
//
// This is a heuristic, unlike the PREVCLOSE ratio which is exact. It would
// also flatten a genuine collapse, which biases results optimistically —
// so every symbol it touches is recorded, and the backtest can be re-run
// excluding them to check the result doesn't depend on this.
const RESIDUAL_DROP = 0.45;
const RESIDUAL_RISE = 2.2;
let residualActions = 0;
const residualSymbols = new Set();

function adjustResiduals(bars, sym) {
  const factors = new Array(bars.length).fill(1);
  let cum = 1;
  let hit = false;
  for (let i = bars.length - 1; i >= 1; i--) {
    const prior = bars[i - 1].close;
    if (prior > 0) {
      const r = bars[i].close / prior;
      if (r < RESIDUAL_DROP || r > RESIDUAL_RISE) {
        const gap = (new Date(bars[i].date) - new Date(bars[i - 1].date)) / 86400000;
        if (gap <= MAX_GAP_DAYS) { cum *= r; residualActions++; hit = true; }
        else gapsSkipped++;
      }
    }
    factors[i - 1] = cum;
  }
  if (!hit) return;
  residualSymbols.add(sym);
  for (let i = 0; i < bars.length; i++) {
    const f = factors[i];
    if (f === 1) continue;
    bars[i].open *= f;
    bars[i].high *= f;
    bars[i].low *= f;
    bars[i].close *= f;
    bars[i].volume = Math.round(bars[i].volume / f);
  }
}

const bySymbol = new Map();
const universe = new Map();
let files = 0, rows = 0;

function record(sym, date, o, h, l, c, v, val, pc, isin) {
  if (!(c > 0)) return;
  let arr = bySymbol.get(sym);
  if (!arr) { arr = []; bySymbol.set(sym, arr); }
  arr.push(`${date},${o},${h},${l},${c},${v},${val},${pc}`);
  const u = universe.get(sym);
  if (!u) universe.set(sym, { first: date, last: date, days: 1, isin });
  else {
    if (date < u.first) u.first = date;
    if (date > u.last) u.last = date;
    u.days++;
    if (isin && !u.isin) u.isin = isin;
  }
  rows++;
}

const years = (await fs.readdir(SRC, { withFileTypes: true }))
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

for (const y of years) {
  const dir = path.join(SRC, y);
  for (const f of (await fs.readdir(dir)).filter((n) => n.endsWith(".zip"))) {
    const date = dateFromFilename(f);
    if (!date) continue;
    let text;
    try {
      text = unzipSingle(await fs.readFile(path.join(dir, f)));
    } catch {
      continue; // a truncated download; re-run the fetcher to repair it
    }
    const lines = text.split("\n");

    if (lines[0].startsWith("SYMBOL,SERIES")) {
      for (let i = 1; i < lines.length; i++) {
        const p = lines[i].split(",");
        // Pre-2011 files carry 11 columns, not 13 — no TOTALTRADES, no ISIN.
        // Requiring 13 silently discarded every row from 2006 to 2011,
        // taking the 2008 crash out of the backtest entirely.
        if (p.length < 11 || (p[1] !== "EQ" && p[1] !== "BE")) continue;
        record(p[0].trim(), date, +p[2], +p[3], +p[4], +p[5], +p[8], +p[9], +p[7], (p[12] || "").trim());
      }
    } else {
      const cols = lines[0].trim().split(",");
      const ix = Object.fromEntries(cols.map((c, i) => [c.trim(), i]));
      for (let i = 1; i < lines.length; i++) {
        const p = lines[i].split(",");
        if (p.length < cols.length - 4) continue;
        // The UDiFF feed carries gold bonds, ETFs and derivatives too.
        if (p[ix.FinInstrmTp] !== "STK") continue;
        if (p[ix.SctySrs] !== "EQ" && p[ix.SctySrs] !== "BE") continue;
        record(
          p[ix.TckrSymb].trim(), date,
          +p[ix.OpnPric], +p[ix.HghPric], +p[ix.LwPric], +p[ix.ClsPric],
          +p[ix.TtlTradgVol], +p[ix.TtlTrfVal], +p[ix.PrvsClsgPric], (p[ix.ISIN] || "").trim()
        );
      }
    }
    files++;
    if (files % 500 === 0) {
      console.log(`  parsed ${files} files, ${bySymbol.size} symbols, ${(rows / 1e6).toFixed(2)}M rows`);
    }
  }
}

console.log(`\nparsed ${files} bhavcopies | ${bySymbol.size} distinct symbols | ${(rows / 1e6).toFixed(2)}M daily bars`);

await fs.mkdir(OUT, { recursive: true });
const keys = [...bySymbol.keys()].sort();
let chunk = 0;
for (let i = 0; i < keys.length; i += SYMBOLS_PER_CHUNK) {
  const sub = {};
  for (const k of keys.slice(i, i + SYMBOLS_PER_CHUNK)) {
    sub[`${k}.NS`] = bySymbol
      .get(k)
      .map((line) => {
        const [date, o, h, l, c, v, val, pc] = line.split(",");
        return { date, open: +o, high: +h, low: +l, close: +c, volume: +v, value: +val, prevClose: +pc };
      })
      .sort((a, b) => (a.date < b.date ? -1 : a.date > b.date ? 1 : 0));
    backAdjust(sub[`${k}.NS`]);
    adjustResiduals(sub[`${k}.NS`], k);
  }
  await fs.writeFile(path.join(OUT, `${BASE}.part${chunk}.json`), JSON.stringify(sub));
  chunk++;
}
await fs.writeFile(path.join(OUT, `${BASE}.manifest.json`), JSON.stringify({ symbolCount: keys.length, chunkCount: chunk }));
await fs.writeFile(path.join(OUT, "bhav-universe-240mo.json"), JSON.stringify(Object.fromEntries(universe)));

const gone = [...universe.values()].filter((u) => u.last < "2026-08-01").length;
console.log(`wrote ${chunk} chunks + universe index to ${OUT}`);
console.log(`${actionsFound} corporate actions (splits/bonuses) detected and back-adjusted`);
console.log(`${residualActions} residual >55% gaps adjusted heuristically across ${residualSymbols.size} symbols`);
console.log(`${gapsSkipped} apparent actions IGNORED because they sat across a hole in the series`);
await fs.writeFile(path.join(OUT, "bhav-residual-actions.json"), JSON.stringify([...residualSymbols]));
console.log(`${gone} of ${keys.length} symbols stopped trading during the window — these are what survivorship bias hides.`);
